
Create table tokens(
	token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	token_value varchar(500) not null unique,
	token_expiry_time timestamp
);
-- users
create table users
(
	user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_name VARCHAR(100) NOT NULL,

    user_email VARCHAR(100) NOT NULL UNIQUE,

    user_password VARCHAR(255) NOT NULL,

    user_phone VARCHAR(15),

    user_avatar VARCHAR(500),

    user_gender VARCHAR(50),
    
    user_birthday DATE,
    
    user_address VARCHAR(255),
    
	user_role VARCHAR(20) NOT NULL DEFAULT 'STUDENT'
    CHECK (user_role IN ('STUDENT', 'OWNER', 'ADMIN'))
);
-- motels
CREATE TABLE motels(
    motel_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id bigint not null,
	motel_name VARCHAR(200),	
	motel_address VARCHAR(300),
	motel_owner VARCHAR(300),

	foreign key(user_id) references users(user_id)
 );

 -- rooms
CREATE TABLE rooms
(
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 
	motel_id BIGINT NOT NULL,

    room_price DECIMAL(12,2) NOT NULL,

    room_deposit DECIMAL(12,2) DEFAULT 0, /* tiền đặt cọc */

    room_area DOUBLE PRECISION,

    room_address VARCHAR(255),

    room_type VARCHAR(100),
    
    room_status VARCHAR(100),
	room_view integer, 
    
    room_description VARCHAR(6000),
	
	foreign key(motel_id) references motels(motel_id)
);

-- user_room 
CREATE TABLE user_room (
    user_room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
	
    start_date DATE NOT NULL,
    end_date DATE,
    monthly_rent DECIMAL(12,2) NOT NULL,
    contract_status VARCHAR(20),

    FOREIGN KEY (user_id) REFERENCES users(user_id),
    FOREIGN KEY (room_id) REFERENCES rooms(room_id)
);
   

   CREATE TABLE services
(
    service_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    service_name VARCHAR(100) NOT NULL UNIQUE,

	service_time integer,
	service_price DECIMAL(12,2),

    service_icon VARCHAR(255),

    service_status varchar(200)
);

CREATE TABLE room_services(
	room_id BIGINT NOT NULL,
	service_id BIGINT NOT NULL,
	
	PRIMARY KEY(room_id, service_id),
	FOREIGN KEY (room_id) references  rooms(room_id),
	FOREIGN KEY (service_id) references services(service_id)
);


CREATE TABLE amenities(
	amenity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	amenity_name VARCHAR(100)NOT NULL UNIQUE

);

CREATE TABLE room_amenities
(
	room_id BIGINT NOT NULL,
	amenity_id BIGINT NOT NULL,
	amenity_quantity INT NOT NULL DEFAULT 1,
	primary key(room_id, amenity_id),
	FOREIGN KEY(room_id) references rooms(room_id),
	FOREIGN KEY(amenity_id) references amenities(amenity_id)
);


CREATE TABLE universities
(
	university_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	university_name VARCHAR(200) not null,
	university_code VARCHAR(50) UNIQUE,
    university_address VARCHAR(300),
    university_city VARCHAR(100),
    university_district VARCHAR(100),
    university_logo VARCHAR(500),
    university_website VARCHAR(300),
	university_phone varchar(15),
    university_status VARCHAR(20)
);

create table motel_universities
(
	motel_id bigint not null,
	university_id bigint not null,

	primary key(motel_id,university_id),
	FOREIGN KEY(motel_id) references motels(motel_id),
	FOREIGN KEY(university_id) references universities(university_id)
);


create table posts
(
	post_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id bigint not null,
	room_id bigint not null,

	post_title varchar(100),
	post_content text,
	post_create_at timestamp,
	post_status varchar(100),
	post_view INTEGER,
	foreign key(user_id) references users(user_id),
	foreign key(room_id) references rooms(room_id)
);

CREATE TABLE images
(
	image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

	post_id bigint ,
	room_id bigint ,
	motel_id bigint, 
	
	image_name varchar(100),
	images_url varchar(300),

	FOREIGN KEY (post_id) REFERENCES posts(post_id),
    FOREIGN KEY (room_id) REFERENCES rooms(room_id),
    FOREIGN KEY (motel_id) REFERENCES motels(motel_id),
	CHECK (
    (CASE WHEN post_id IS NOT NULL THEN 1 ELSE 0 END) +
    (CASE WHEN room_id IS NOT NULL THEN 1 ELSE 0 END) +
    (CASE WHEN motel_id IS NOT NULL THEN 1 ELSE 0 END) = 1
)
);

