CREATE TABLE rental_requests (
    rental_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES users(user_id),
    room_id BIGINT NOT NULL REFERENCES rooms(room_id),
    requested_start_date DATE NOT NULL,
    requested_rent DECIMAL(12,2) NOT NULL,
    message VARCHAR(1000),
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_rental_requests_student_created
    ON rental_requests (student_id, created_at DESC);
CREATE INDEX idx_rental_requests_room_status
    ON rental_requests (room_id, status);
